async def seed_hospitals() -> int:
    """Upsert all hospitals; safe to run on every startup."""
    db = get_db()
    count = 0
    for h in HOSPITALS:
        await db.hospitals.update_one({"id": h["id"]}, {"$set": h}, upsert=True)
        count += 1
    logger.info("Seeded %s hospitals", count)
    return count
