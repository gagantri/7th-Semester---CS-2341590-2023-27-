def _value_score(price: int, quality: int, availability: int, trust: int) -> dict:
    overall = round(
        price * 0.35 + quality * 0.40 + availability * 0.15 + trust * 0.10
    )
    return {
        "overall": overall,
        "price": price,
        "quality": quality,
        "availability": availability,
        "trust": trust,
    }


def _beds(total: int, icu: int, free_gen_pct: float, free_icu_pct: float) -> dict:
    return {
        "total_beds": total,
        "icu_beds": icu,
        "free_general_beds": int((total - icu) * free_gen_pct),
        "free_icu_beds": max(0, int(icu * free_icu_pct)),
        "last_updated": TODAY,
    }


